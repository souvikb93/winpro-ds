// Generates src/stories/<category>/<Name>.stories.tsx from script./story-data.mjs and components.json. Run: npm run stories
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { SPEC } from './story-data.mjs';

const root = new URL('../', import.meta.url).pathname;
const catalog = JSON.parse(readFileSync(join(root, 'components.json'), 'utf8')).components;
const slug = (s) => s.toLowerCase().replace(/[^a-z]+/g, '-');

rmSync(join(root, 'src/stories'), { recursive: true, force: true });
const missing = Object.keys(catalog).filter((n) => !SPEC.some((s) => s.n === n));
if (missing.length) console.warn('no story spec for:', missing.join(', '));

for (const s of SPEC) {
  const c = catalog[s.n];
  if (!c) throw new Error(`spec for unknown component ${s.n}`);
  const used = new Set([s.n, ...(s.extra ?? []), ...(s.scale ? ['Stack', 'Text'] : [])]);
  const dir = join(root, 'src/stories', slug(c.category));
  mkdirSync(dir, { recursive: true });
  const figma = c.figma ? ` Figma: ${c.figma}.` : '';
  const anyArgs = (src) => src.replace(/^\(args\) =>/, '(args: any) =>');
  const docs = s.overlay ? `docs: { description: { component: DESCRIPTION }, story: { inline: false, iframeHeight: 420 } }` : `docs: { description: { component: DESCRIPTION } }`;
  const stories = Object.entries(s.stories ?? {}).map(([name, a]) => `export const ${name}: Story = { args: ${a} as never };`).join('\n');
  const scale = s.scale ? `\n/** The whole type scale, one line each. */\nexport const Scale: Story = { render: () => <Stack gap="2">{${s.scale}}</Stack>, parameters: { controls: { disable: true } } };\n` : '';
  writeFileSync(join(dir, `${s.n}.stories.tsx`), `// GENERATED by scripts/build-stories.mjs from script./story-data.mjs. Edit the spec, then run \`npm run stories\`.
import * as React from 'react';
import type { Meta, StoryObj } from '@storybook/react-vite';

import { ${[...used].join(', ')} } from '../../ds';

const meta = {
  title: ${JSON.stringify(`${c.category}/${s.n}`)},
  component: ${s.n},
  tags: ['autodocs'],
  parameters: { ${docs.replace('DESCRIPTION', JSON.stringify(c.description + figma))}${s.tall ? ", layout: 'padded'" : ''} },
  args: ${s.args} as never,
} satisfies Meta<typeof ${s.n}>;
export default meta;
type Story = StoryObj<typeof meta>;

/** Interactive: change the props in the Controls table. */
export const Default: Story = {${s.render ? ` render: ${anyArgs(s.render)},` : ''} };
${stories}${scale}`);
}
console.log(SPEC.length, 'story files');
